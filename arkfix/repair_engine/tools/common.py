def _read_ide_sdk_location() -> Path | None:
    appdata = os.environ.get("APPDATA")
    if not appdata:
        return None

    huawei_dir = Path(appdata) / "Huawei"
    if not huawei_dir.is_dir():
        return None

    option_files = sorted(huawei_dir.glob("DevEcoStudio*/options/other.xml"), reverse=True)
    for option_file in option_files:
        try:
            content = option_file.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        match = DEV_ECO_SDK_LOCATION_RE.search(content)
        if not match:
            continue
        sdk_text = match.group(1).replace("\\\\", "\\").strip()
        if not sdk_text:
            continue
        sdk_path = Path(sdk_text).expanduser()
        if sdk_path.exists():
            return sdk_path.resolve()
    return None


def find_deveco_sdk_roots(deveco_path: str | os.PathLike[str]) -> list[Path]:
    base_path = resolve_directory(deveco_path, "deveco_path")
    tool_env = build_tool_process_env()

    raw_candidates: list[Path] = []

    env_sdk = _first_non_empty_text(
        tool_env.get("OHOS_BASE_SDK_HOME"),
        tool_env.get("DEVECO_SDK_HOME"),
        tool_env.get("HARMONY_SDK_HOME"),
        tool_env.get("HOS_SDK_HOME"),
    )
    if env_sdk:
        raw_candidates.extend(_sdk_related_candidates(Path(env_sdk)))

    ide_sdk = _read_ide_sdk_location()
    if ide_sdk:
        raw_candidates.extend(_sdk_related_candidates(ide_sdk))

    raw_candidates.extend(_sdk_related_candidates(base_path))

    sibling_names = ("HarmonySDK", "huawei_sdk", "HuaweiSDK")
    for sibling_name in sibling_names:
        sibling = base_path.parent / sibling_name
        if sibling.exists():
            raw_candidates.extend(_sdk_related_candidates(sibling))

    sdk_roots: list[Path] = []
    seen: set[Path] = set()
    for candidate in raw_candidates:
        resolved = candidate.resolve()
        if resolved in seen:
            continue
        seen.add(resolved)
        if _looks_like_sdk_root(resolved):
            sdk_roots.append(resolved)
    return sdk_roots


def find_deveco_sdk_root(deveco_path: str | os.PathLike[str]) -> Path | None:
    sdk_roots = find_deveco_sdk_roots(deveco_path)
    return sdk_roots[0] if sdk_roots else None


def _node_home_has_executable(path: Path) -> bool:
    executable_name = "node.exe" if os.name == "nt" else "node"
    return path.is_dir() and (path / executable_name).is_file()


def find_node_home(deveco_path: str | os.PathLike[str]) -> Path | None:
    base_path = resolve_directory(deveco_path, "deveco_path")
    tool_env = build_tool_process_env()

    env_node_home = _first_non_empty_text(tool_env.get("HARMONY_NODE_HOME"), tool_env.get("NODE_HOME"))
    if env_node_home:
        candidate = Path(env_node_home).expanduser().resolve()
        if _node_home_has_executable(candidate):
            return candidate

    executable_name = "node.exe" if os.name == "nt" else "node"
    candidates = _existing_paths(
        [
            base_path / "tools" / "node",
            base_path / "node",
        ]
    )
    for candidate in candidates:
        if (candidate / executable_name).exists():
            return candidate

    recursive_match = next(base_path.rglob(executable_name), None)
    if recursive_match:
        return recursive_match.parent.resolve()

    return None


def find_ohpm(deveco_path: str | os.PathLike[str]) -> Path | None:
    base_path = resolve_directory(deveco_path, "deveco_path")
    candidates = [
        base_path / "tools" / "ohpm" / "bin" / "ohpm.bat",
        base_path / "tools" / "ohpm" / "bin" / "ohpm",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate.resolve()
    return None


def find_java_home(deveco_path: str | os.PathLike[str]) -> Path | None:
    env_java_home = _first_non_empty_text(os.environ.get("JAVA_HOME"))
    if env_java_home:
        home = Path(env_java_home).expanduser().resolve()
        executable_name = "java.exe" if os.name == "nt" else "java"
        if (home / "bin" / executable_name).is_file():
            return home
    if shutil.which("java"):
        return None

    base_path = resolve_directory(deveco_path, "deveco_path")
    executable_name = "java.exe" if os.name == "nt" else "java"
    for home_name in ("jbr", "jre"):
        home = base_path / home_name
        if (home / "bin" / executable_name).is_file():
            return home.resolve()

    jdk_bin = base_path / "tools" / "jdk" / "bin" / executable_name
    if jdk_bin.is_file():
        return jdk_bin.parent.parent.resolve()

    found = next(base_path.rglob(executable_name), None)
    if found and found.parent.name == "bin":
        return found.parent.parent.resolve()
    return None


def _is_usable_hvigor_wrapper(path: Path) -> bool:
    if not path.is_file():
        return False

    wrapper_dir = path.parent
    try:
        wrapper_text = path.read_text(encoding="utf-8", errors="replace").lower().replace("/", "\\")
    except OSError:
        return False

    expected_entrypoints: list[Path] = []
    if "hvigorw.js" in wrapper_text:
        expected_entrypoints.append(wrapper_dir / "hvigorw.js")
    if "hvigor\\hvigor-wrapper.js" in wrapper_text:
        expected_entrypoints.append(wrapper_dir / "hvigor" / "hvigor-wrapper.js")
    elif "hvigor-wrapper.js" in wrapper_text:
        expected_entrypoints.append(wrapper_dir / "hvigor-wrapper.js")

    if not expected_entrypoints:
        return True
    return any(entrypoint.is_file() for entrypoint in expected_entrypoints)


def build_deveco_tool_env(
    deveco_path: str | os.PathLike[str],
    *,
    sdk_root: str | os.PathLike[str] | None = None,
    include_ohpm: bool = True,
) -> dict[str, str]:
    env = build_tool_process_env()
    for key in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"):
        env.pop(key, None)
    shared_tool_home = (
        Path(__file__).resolve().parents[3] / "evaluation" / "command_line_tools_test"
    ).resolve()
    env["HOME"] = str(shared_tool_home)
    env["USERPROFILE"] = str(shared_tool_home)
    env["HVIGOR_USER_HOME"] = str((shared_tool_home / ".hvigor").resolve())
    deveco_dir = resolve_directory(deveco_path, "deveco_path")
    prepend_paths: list[str] = []

    if sdk_root:
        sdk_path = Path(sdk_root).expanduser().resolve()
        env["OHOS_BASE_SDK_HOME"] = str(sdk_path)
        env["OHOS_SDK_HOME"] = str(sdk_path)
        env["DEVECO_SDK_HOME"] = str(sdk_path)
        env["HOS_SDK_HOME"] = str(sdk_path)

    node_home = find_node_home(deveco_dir)
    if node_home:
        env["NODE_HOME"] = str(node_home)
        prepend_paths.append(str(node_home))

    java_home = find_java_home(deveco_dir)
    if java_home:
        env["JAVA_HOME"] = str(java_home)
        prepend_paths.append(str(java_home / "bin"))

    if include_ohpm:
        ohpm = find_ohpm(deveco_dir)
        if ohpm:
            prepend_paths.append(str(ohpm.parent))

    if prepend_paths:
        prepend_env_path(env, prepend_paths)
    return env


def _candidate_sdk_dirs_from_env(base_env: Mapping[str, str] | None) -> list[Path]:
    env = base_env or os.environ
    ordered: list[Path] = []
    seen: set[str] = set()
    for key in ("DEVECO_SDK_HOME", "OHOS_BASE_SDK_HOME", "OHOS_SDK_HOME", "HOS_SDK_HOME"):
        raw = str(env.get(key, "")).strip()
        if not raw:
            continue
        if raw.lower() in seen:
            continue
        seen.add(raw.lower())
        ordered.append(Path(raw))
    return ordered


def _normalize_sdk_dir_for_local_properties(path_value: str | os.PathLike[str]) -> str:
    return Path(path_value).expanduser().resolve().as_posix()


def ensure_local_properties(
    repo_dir: str | os.PathLike[str],
    *,
    sdk_root: str | os.PathLike[str] | None = None,
    sdk_api_level: int | None = None,
    base_env: Mapping[str, str] | None = None,
) -> Path:
    """Ensure ``<repo>/local.properties`` contains ``sdk.dir`` for the selected SDK root."""

    resolved_repo = resolve_directory(repo_dir, "repo_dir")
    candidates: list[Path] = []
    if sdk_root is not None:
        candidates.append(Path(sdk_root))
    candidates.extend(_candidate_sdk_dirs_from_env(base_env))

    selected_sdk: Path | None = None
    seen: set[str] = set()
    for candidate in candidates:
        try:
            resolved = candidate.expanduser().resolve()
        except OSError:
            continue
        key = str(resolved).lower()
        if key in seen:
            continue
        seen.add(key)
        if resolved.exists():
            selected_sdk = resolved
            break

    if selected_sdk is None:
        raise StructuredToolError(
            code="local_properties_sdk_missing",
            message=(
                "Unable to create local.properties because no SDK root was available from "
                "DEVECO_SDK_HOME / OHOS_BASE_SDK_HOME / OHOS_SDK_HOME / HOS_SDK_HOME."
            ),
            details={
                "repo_dir": str(resolved_repo),
                "sdk_root_fallback": str(Path(sdk_root).expanduser()) if sdk_root is not None else "",
                "sdk_api_level": sdk_api_level,
                "env_candidates": [str(path) for path in _candidate_sdk_dirs_from_env(base_env)],
            },
        )

    content = AUTO_LOCAL_PROPERTIES_HEADER + "\n" + f"sdk.dir={_normalize_sdk_dir_for_local_properties(selected_sdk)}\n"
    target = resolved_repo / "local.properties"
    existing = target.read_text(encoding="utf-8", errors="replace") if target.is_file() else ""
    if existing != content:
        write_text_file(target, content)
    return target


def find_hvigor_wrapper(
    repo_path: str | os.PathLike[str],
    deveco_path: str | os.PathLike[str],
) -> Path:
    repo_dir = resolve_directory(repo_path, "repo_path")
    deveco_dir = resolve_directory(deveco_path, "deveco_path")

    wrapper_names = ("hvigorw.bat", "hvigorw") if os.name == "nt" else ("hvigorw", "hvigorw.bat")

    repo_candidates = [repo_dir / name for name in wrapper_names]
    deveco_candidates = [
        deveco_dir / "tools" / "hvigor" / "bin" / "hvigorw.bat",
        deveco_dir / "tools" / "hvigor" / "bin" / "hvigorw",
        deveco_dir / "hvigorw.bat",
        deveco_dir / "hvigorw",
    ]

    for candidate in repo_candidates + deveco_candidates:
        if _is_usable_hvigor_wrapper(candidate):
            return candidate.resolve()

    for name in wrapper_names:
        for recursive_match in deveco_dir.rglob(name):
            if _is_usable_hvigor_wrapper(recursive_match):
                return recursive_match.resolve()

    raise FileNotFoundError(
        "Unable to find hvigorw/hvigorw.bat under the repo or the provided DevEco Studio path."
    )


def _repo_oh_package_paths(repo_dir: Path) -> list[Path]:
    ignored_parts = {
        ".git",
        ".hvigor",
        ".preview",
        "build",
        "node_modules",
        "oh_modules",
    }
    paths: list[Path] = []
    for path in repo_dir.rglob("oh-package.json5"):
        if any(part in ignored_parts for part in path.relative_to(repo_dir).parts[:-1]):
            continue
        paths.append(path)
    return sorted(paths)


def _is_registry_dependency_spec(spec: Any) -> bool:
    if not isinstance(spec, str):
        return False
    stripped = spec.strip()
    if not stripped:
        return False
    lowered = stripped.lower()
    if lowered.startswith(("file:", "path:", "http:", "https:", "./", "../", "/")):
        return False
    if re.match(r"^[a-zA-Z]:[\\/]", stripped):
        return False
    return True


def _minimum_version_from_ohpm_range(spec: Any) -> str | None:
    if not isinstance(spec, str):
        return None
    stripped = spec.strip()
    if not stripped:
        return None
    match = OHPM_SEMVER_RANGE_MIN_RE.match(stripped)
    if not match:
        return None
    version = match.group("version")
    return None if stripped == version else version


def _apply_api_compatible_ohpm_adapters(repo_dir: Path) -> tuple[dict[Path, str], list[str]]:
    backups: dict[Path, str] = {}
    notes: list[str] = []

    for pkg_path in _repo_oh_package_paths(repo_dir):
        try:
            original = pkg_path.read_text(encoding="utf-8", errors="replace")
            data = parse_json5_text(original)
        except Exception:
            continue
        if not isinstance(data, dict):
            continue

        changed = False
        for section_name in ("dependencies", "dynamicDependencies", "devDependencies"):
            section = data.get(section_name)
            if not isinstance(section, dict):
                continue
            for package_name, spec in list(section.items()):
                minimum_version = _minimum_version_from_ohpm_range(spec)
                if _is_registry_dependency_spec(spec) and minimum_version is not None:
                    section[package_name] = minimum_version
                    changed = True
                    notes.append(
                        "ENV_PREPARE_OHPM_ADAPTER=pin_minimum "
                        f"{package_name} {spec!r}->{minimum_version!r} "
                        f"in {format_path_for_display(pkg_path, start=repo_dir)}"
                    )

        if changed:
            backups[pkg_path] = original
            pkg_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    return backups, notes


def _snapshot_files(paths: Iterable[Path]) -> dict[Path, str | None]:
    snapshots: dict[Path, str | None] = {}
    for path in paths:
        resolved = path.resolve()
        if resolved.is_file():
            snapshots[resolved] = resolved.read_text(encoding="utf-8", errors="replace")
        else:
            snapshots[resolved] = None
    return snapshots


def _restore_file_snapshots(snapshots: Mapping[Path, str | None]) -> list[str]:
    notes: list[str] = []
    for path, content in snapshots.items():
        try:
            if content is None:
                if path.exists():
                    path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        except Exception as exc:
            notes.append(f"ENV_PREPARE_RESTORE_ERROR={path}: {exc}")
    return notes


def run_ohpm_install(
    repo_dir: str | os.PathLike[str],
    deveco_path: str | os.PathLike[str],
    *,
    timeout_sec: float | None = None,
) -> tuple[int, str]:
    resolved_repo = resolve_directory(repo_dir, "repo_dir")
    resolved_deveco = resolve_directory(deveco_path, "deveco_path")
    ohpm = find_ohpm(resolved_deveco)
    if ohpm is None:
        raise FileNotFoundError(f"Unable to find ohpm under {resolved_deveco}")

    offline_env = Path(
        os.environ.get("ARKEVAL_OFFLINE_ENV_ROOT")
        or (Path(__file__).resolve().parents[3] / "evaluation" / "command_line_tools_test" / "offline_env")
    ).resolve()
    cache_dir = offline_env / "ohpm_cache"
    cache_dir.mkdir(parents=True, exist_ok=True)
    command = [
        str(ohpm),
        "install",
        "--cache",
        str(cache_dir),
        "--registry",
        "https://repo.harmonyos.com/ohpm/",
    ]
    lock_paths = [path.parent / "oh-package-lock.json5" for path in _repo_oh_package_paths(resolved_repo)]
    lock_snapshots = _snapshot_files(lock_paths)
    manifest_backups: dict[Path, str] = {}
    adapter_notes: list[str] = []
    restore_notes: list[str] = []
    env = build_deveco_tool_env(resolved_deveco)
    env["HOME"] = str(offline_env)
    env["USERPROFILE"] = str(offline_env)
    env["OHPM_CACHE"] = str(cache_dir)
    env["OHPM_STORE_DIR"] = str(offline_env / "ohpm_store")
    try:
        manifest_backups, adapter_notes = _apply_api_compatible_ohpm_adapters(resolved_repo)
        install_lock = offline_env / "arkeval-ohpm-install.lock"
        with FileLock(str(install_lock), timeout=max(900.0, float(timeout_sec or 0))):
            result = run_command(command, cwd=resolved_repo, env=env, timeout_sec=timeout_sec)
    finally:
        restore_notes.extend(_restore_file_snapshots({path: text for path, text in manifest_backups.items()}))
        restore_notes.extend(_restore_file_snapshots(lock_snapshots))

    output_text = command_output(result)
    status = "SUCCESS" if result.returncode == 0 else "FAILED"
    combined = "\n".join(
        [
            f"ENV_PREPARE_OHPM_STATUS={status}",
            f"ENV_PREPARE_OHPM_EXIT_CODE={result.returncode}",
            f"ENV_PREPARE_OHPM_COMMAND={format_command(command)}",
            *adapter_notes,
            output_text.strip(),
            *restore_notes,
        ]
    ).strip()
    return result.returncode, combined + "\n"


def _abi_filter_text_with_x86_64(text: str, *, only_x86_64: bool = False) -> str:
    pattern = re.compile(r'("abiFilters"\s*:\s*\[)(?P<body>.*?)(\])', re.S)
    match = pattern.search(text)
    if not match:
        return text
    body = match.group("body")
    if only_x86_64:
        new_body = '\n        "x86_64"\n      '
        return text[: match.start("body")] + new_body + text[match.end("body") :]
    if re.search(r'["\']x86_64["\']', body):
        return text
    stripped = body.rstrip()
    if stripped:
        suffix = "" if stripped.endswith(",") else ","
        new_body = f'{stripped}{suffix}\n        "x86_64"\n      '
    else:
        new_body = '\n        "x86_64"\n      '
    return text[: match.start("body")] + new_body + text[match.end("body") :]


def _imageknife_root_profile_with_gpu_transform(root_profile: Path) -> str | None:
    if not root_profile.is_file():
        return None

    original = root_profile.read_text(encoding="utf-8", errors="replace")
    try:
        data = parse_json5_text(original)
    except Exception:
        return None

    modules = data.get("modules") if isinstance(data, dict) else None
    if not isinstance(modules, list):
        return None
    for module in modules:
        if isinstance(module, dict) and module.get("name") == "gpu_transform":
            return None

    modules.append({
        "name": "gpu_transform",
        "srcPath": "./gpu_transform",
    })
    write_text_file(root_profile, json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    return original


def _run_hvigor_preprocess_task(
    repo_dir: Path,
    deveco_dir: Path,
    *,
    module: str,
    product: str,
    task: str,
    sdk_root: Path | None,
    sdk_api_level: int | None,
    timeout_sec: float | None,
) -> str:
    hvigor = find_hvigor_wrapper(repo_dir, deveco_dir)
    command = [
        str(hvigor),
        "--debug",
        "--no-daemon",
        "--mode",
        "module",
        "-p",
        f"module={module}",
        "-p",
        f"product={product}",
        task,
    ]
    env = build_deveco_tool_env(deveco_dir, sdk_root=sdk_root)
