def _safe_remove_generated_dir(path: Path, *, owner: Path) -> None:
    resolved_owner = owner.expanduser().resolve()
    resolved_path = path.expanduser().resolve() if path.exists() else path.expanduser().absolute()
    owner_text = str(resolved_owner).lower()
    path_text = str(resolved_path).lower()
    if path_text == owner_text or not path_text.startswith(owner_text + os.sep):
        raise StructuredToolError(
            code="generated_dir_outside_owner",
            message="Refusing to remove a generated directory outside the expected owner.",
            details={"path": str(resolved_path), "owner": str(resolved_owner)},
        )
    if path.exists() or path.is_symlink():
        shutil.rmtree(path)


