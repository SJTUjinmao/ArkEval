def parse_json5_text(text: str) -> Any:
    """
    Parse a subset of JSON5 suitable for Harmony ``build-profile.json5``:
    block comments ``/* */``, line comments ``//``, trailing commas.
    """
    out: list[str] = []
    i = 0
    in_string = False
    quote = ""
    escape = False
    while i < len(text):
        char = text[i]
        next_char = text[i + 1] if i + 1 < len(text) else ""
        if in_string:
            out.append(char)
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == quote:
                in_string = False
            i += 1
            continue
        if char in ("'", '"'):
            in_string = True
            quote = char
            out.append(char)
            i += 1
            continue
        if char == "/" and next_char == "/":
            i += 2
            while i < len(text) and text[i] not in "\r\n":
                i += 1
            continue
        if char == "/" and next_char == "*":
            i += 2
            while i + 1 < len(text) and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2 if i + 1 < len(text) else 0
            continue
        out.append(char)
        i += 1
    stripped = "".join(out)
    for _ in range(32):
        next_text = re.sub(r",(\s*[\]}])", r"\1", stripped)
        if next_text == stripped:
            break
        stripped = next_text
    return json.loads(stripped)


def _coerce_sdk_version(value: Any) -> int | None:
    if value is None:
        return None
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        stripped = value.strip()
        if stripped.isdigit():
            return int(stripped)
        paren_match = re.search(r"\((\d+)\)", stripped)
        if paren_match:
            return int(paren_match.group(1))
    return None


def _read_build_profile_product_info(
    repo_dir: str | os.PathLike[str],
    *,
    product_name: str = "default",
) -> tuple[int | None, int | None, str, str | None]:
    root = Path(repo_dir).expanduser().resolve()
    profile = root / "build-profile.json5"
    if not profile.is_file():
        return None, None, product_name, None

    raw = profile.read_text(encoding="utf-8", errors="replace")
    data = parse_json5_text(raw)
    app = data.get("app") if isinstance(data, dict) else None
    if not isinstance(app, dict):
        return None, None, product_name, None

    products = app.get("products")
    if not isinstance(products, list) or not products:
        return None, None, product_name, None

    selected: dict[str, Any] | None = None
    for entry in products:
        if not isinstance(entry, dict):
            continue
        if entry.get("name") == product_name:
            selected = entry
            break

    if selected is None:
        first = products[0]
        selected = first if isinstance(first, dict) else None
        if selected and isinstance(selected.get("name"), str):
            product_name = selected["name"]

    if selected is None:
        return None, None, product_name, None

    compile_v = _coerce_sdk_version(selected.get("compileSdkVersion"))
    compatible_v = _coerce_sdk_version(selected.get("compatibleSdkVersion"))
    runtime_os = selected.get("runtimeOS")
    return compile_v, compatible_v, product_name, runtime_os if isinstance(runtime_os, str) else None


def read_build_profile_sdk_versions(
    repo_dir: str | os.PathLike[str],
    *,
    product_name: str = "default",
) -> tuple[int | None, int | None, str]:
    """
    Read ``build-profile.json5`` under ``repo_dir`` and return
    ``(compileSdkVersion, compatibleSdkVersion, matched_product_name)``.
    If the product is not found, uses the first product entry when present.
    """
    compile_v, compatible_v, used_product, _runtime_os = _read_build_profile_product_info(
        repo_dir,
        product_name=product_name,
    )
    return compile_v, compatible_v, used_product


def _candidate_openharmony_api_dirs(sdk_root: Path, api_level: int) -> list[Path]:
    level = str(api_level)
    return [
        path
        for path in (
            sdk_root / "default" / "openharmony" / level,
            sdk_root / "openharmony" / level,
            sdk_root / level,
        )
        if path.is_dir()
    ]


def apply_vpn_extension_api20_profile_adapter(
    repo_dir: str | os.PathLike[str],
    sdk_roots: Sequence[Path],
    *,
    product_name: str = "default",
) -> list[str]:
    """Temporarily compile API-14 VPN extension samples with the installed API 20 SDK."""

    root = Path(repo_dir).expanduser().resolve()
    profile = root / "build-profile.json5"
    if not profile.is_file():
        return []
    try:
        original = profile.read_text(encoding="utf-8")
        data = parse_json5_text(original)
    except (OSError, ValueError, TypeError, json.JSONDecodeError):
        return []

    app = data.get("app") if isinstance(data, dict) else None
    products = app.get("products") if isinstance(app, dict) else None
    modules = data.get("modules") if isinstance(data, dict) else None
    if not isinstance(products, list) or not isinstance(modules, list):
        return []
    product = next(
        (item for item in products if isinstance(item, dict) and item.get("name") == product_name),
        None,
    )
    if not isinstance(product, dict):
        return []
    if (
        _coerce_sdk_version(product.get("compileSdkVersion")) != 14
        or _coerce_sdk_version(product.get("targetSdkVersion")) != 14
        or _coerce_sdk_version(product.get("compatibleSdkVersion")) != 14
        or str(product.get("runtimeOS") or "").casefold() != "openharmony"
    ):
        return []

    vpn_manifest: Path | None = None
    for module in modules:
        src_path = module.get("srcPath") if isinstance(module, dict) else None
        if not isinstance(src_path, str) or not src_path.strip():
            continue
        manifest = (root / src_path / "src" / "main" / "module.json5").resolve()
        try:
            manifest.relative_to(root)
            module_data = parse_json5_text(manifest.read_text(encoding="utf-8"))
        except (OSError, ValueError, TypeError, json.JSONDecodeError):
            continue
        module_config = module_data.get("module") if isinstance(module_data, dict) else None
        extensions = module_config.get("extensionAbilities") if isinstance(module_config, dict) else None
        if isinstance(extensions, list) and any(
            isinstance(item, dict) and item.get("type") == "vpn" for item in extensions
        ):
            vpn_manifest = manifest
            break
    if vpn_manifest is None:
        return []

    def schema_support(api_level: int) -> bool | None:
        schemas = [
            api_dir / "toolchains" / "modulecheck" / "module.json"
            for sdk_root in sdk_roots
            for api_dir in _candidate_openharmony_api_dirs(Path(sdk_root), api_level)
            if (api_dir / "toolchains" / "modulecheck" / "module.json").is_file()
        ]
        if not schemas:
            return None
        for schema in schemas:
            try:
                if '"vpn"' in schema.read_text(encoding="utf-8"):
                    return True
            except OSError:
                continue
        return False

    if schema_support(14) is not False or schema_support(20) is not True:
        return []

    pattern = re.compile(r'(?P<prefix>(?:"compileSdkVersion"|compileSdkVersion)\s*:\s*)14\b')
    if len(pattern.findall(original)) != 1:
        return []
    patched = pattern.sub(lambda match: f"{match.group('prefix')}20", original, count=1)
    profile.write_text(patched, encoding="utf-8")
    return [
        "ENV_PREPARE_SDK_ADAPTER=vpn_extension_compile_api14_to_api20 "
        f"manifest={vpn_manifest.relative_to(root).as_posix()}"
    ]


def resolve_sdk_api_slice_for_api(
    sdk_root: str | os.PathLike[str],
    api_level: int | None,
) -> Path:
    """
    Resolve the API-specific SDK slice for diagnostics.

    Example:
    - root ``C:\\...\\OpenHarmony\\Sdk`` + API ``12`` -> ``C:\\...\\OpenHarmony\\Sdk\\12``
    - already-sliced root ``C:\\...\\OpenHarmony\\Sdk\\12`` stays unchanged
    """
    resolved = Path(sdk_root).expanduser().resolve()
    if api_level is None:
        return resolved
    if _is_sdk_component_root(resolved):
        return resolved
    candidates = _candidate_openharmony_api_dirs(resolved, api_level)
    for candidate in candidates:
        if _is_sdk_component_root(candidate):
            return candidate.resolve()
    if candidates:
        return candidates[0].resolve()
    return resolved


def sdk_root_contains_openharmony_api(sdk_root: Path, api_level: int) -> bool:
    """Best-effort check that an API-level OpenHarmony SDK slice is installed under ``sdk_root``."""
    for path in _candidate_openharmony_api_dirs(sdk_root, api_level):
        if any(
            (path / marker).is_dir()
            for marker in ("ets", "toolchains", "native", "previewer", "js")
        ):
            return True
    return bool(_candidate_openharmony_api_dirs(sdk_root, api_level))


def rank_sdk_roots_for_build_profile(
    sdk_roots: list[Path],
    *,
    compile_sdk_version: int | None,
    compatible_sdk_version: int | None,
    runtime_os: str | None = None,
) -> tuple[list[Path], int | None]:
    """
    Prefer SDK roots that contain the OpenHarmony API tree for ``compileSdkVersion``,
    then ``compatibleSdkVersion``. Falls back to the original order if nothing matches.
    Returns ``(ordered_roots, api_level_used)``.
    """
    for api in (compile_sdk_version, compatible_sdk_version):
        if api is None:
            continue
        matching = [root for root in sdk_roots if sdk_root_contains_openharmony_api(root, api)]
        if matching:
            tail = [root for root in sdk_roots if root not in matching]
            return matching + tail, api
    return list(sdk_roots), None


def get_ordered_sdk_roots_for_repo(
    repo_dir: str | os.PathLike[str],
    deveco_path: str | os.PathLike[str],
    *,
    product_name: str = "default",
) -> tuple[list[Path], dict[str, Any]]:
    """
    1. Enumerate DevEco / env SDK roots (``find_deveco_sdk_roots``).
    2. Read ``build-profile.json5`` compile / compatible SDK versions.
    3. Re-order roots so roots that contain the matching API level are tried first.

    Returns ``(ordered_roots, meta)`` where ``meta`` includes parsed versions and selection notes.
    """
    repo_path = Path(repo_dir).expanduser().resolve()
    compile_v, compatible_v, used_product, runtime_os = _read_build_profile_product_info(
        repo_path,
        product_name=product_name,
    )
    roots = find_deveco_sdk_roots(deveco_path)
    ranked, api_used = rank_sdk_roots_for_build_profile(
        roots,
        compile_sdk_version=compile_v,
        compatible_sdk_version=compatible_v,
        runtime_os=runtime_os,
    )
    meta: dict[str, Any] = {
        "build_profile_path": str(repo_path / "build-profile.json5"),
        "product": used_product,
        "compileSdkVersion": compile_v,
        "compatibleSdkVersion": compatible_v,
        "runtimeOS": runtime_os,
        "sdk_selection_api_level": api_used,
        "sdk_roots_unfiltered_count": len(roots),
        "sdk_roots_ordered_count": len(ranked),
    }
    if not roots:
        meta["sdk_selection_note"] = (
            "No OpenHarmony SDK root was discovered (check DEVECO_SDK_HOME, DevEco install, or --deveco-path)."
        )
    elif compile_v is not None and api_used is None:
        meta["sdk_selection_note"] = (
            "No SDK root reported an installed OpenHarmony API tree for compile/compatible "
            f"versions ({compile_v}/{compatible_v}); install API {compile_v} in DevEco SDK Manager or fix SDK paths."
        )
    return ranked, meta


def require_sdk_roots_for_repo(
    repo_dir: str | os.PathLike[str],
    deveco_path: str | os.PathLike[str],
    *,
    product_name: str = "default",
) -> tuple[list[Path], dict[str, Any]]:
    """
    Resolve SDK roots for a repo and fail early when no usable OpenHarmony SDK can be matched.
    """
    roots, meta = get_ordered_sdk_roots_for_repo(
        repo_dir,
        deveco_path,
        product_name=product_name,
    )
    note = str(meta.get("sdk_selection_note") or "").strip()
    if not roots:
        raise StructuredToolError(
            code="sdk_not_found",
            message=note or "No OpenHarmony SDK root was discovered.",
            details={"sdk_meta": meta},
        )
    if meta.get("compileSdkVersion") is not None and meta.get("sdk_selection_api_level") is None:
        raise StructuredToolError(
            code="sdk_precheck_failed",
            message=note or "No SDK root matches the compileSdkVersion required by build-profile.json5.",
            details={
                "sdk_meta": meta,
                "sdk_roots": [str(root) for root in roots],
            },
        )
    return roots, meta


