def parse_json5_text(text: str) -> Any:
    """Parse the JSON5 subset used by Harmony ``build-profile.json5`` files."""

    stripped = re.sub(r"/\*[\s\S]*?\*/", "", text)
    stripped = re.sub(r"//[^\n]*", "", stripped)
    for _ in range(32):
        next_text = re.sub(r",(\s*[\]}])", r"\1", stripped)
        if next_text == stripped:
            break
        stripped = next_text
    return json.loads(stripped)


def _coerce_sdk_version(value: Any) -> int | None:
    if value is None or isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        stripped = value.strip()
        if stripped.isdigit():
            return int(stripped)
        match = re.search(r"\((\d+)\)\s*$", stripped)
        if match:
            return int(match.group(1))
    return None


def read_build_profile_sdk_versions(
    repo_dir: str | os.PathLike[str],
    *,
    product_name: str = "default",
) -> tuple[int | None, int | None, str]:
    """Read compile / compatible SDK versions from ``<repo_dir>/build-profile.json5``."""

    root = Path(repo_dir).expanduser().resolve()
    profile = root / "build-profile.json5"
    if not profile.is_file():
        return None, None, product_name

    raw = profile.read_text(encoding="utf-8", errors="replace")
    data = parse_json5_text(raw)
    app = data.get("app") if isinstance(data, dict) else None
    if not isinstance(app, dict):
        return None, None, product_name

    products = app.get("products")
    if not isinstance(products, list) or not products:
        return None, None, product_name

    selected: dict[str, Any] | None = None
    for entry in products:
        if isinstance(entry, dict) and entry.get("name") == product_name:
            selected = entry
            break

    if selected is None:
        first = products[0]
        selected = first if isinstance(first, dict) else None
        if selected and isinstance(selected.get("name"), str):
            product_name = selected["name"]

    if selected is None:
        return None, None, product_name

    compile_v = _coerce_sdk_version(selected.get("compileSdkVersion"))
    compatible_v = _coerce_sdk_version(selected.get("compatibleSdkVersion"))
    return compile_v, compatible_v, product_name
