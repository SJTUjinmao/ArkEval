def _patch_orange_shopping_video_component_ids(path: Path) -> int:
    if not path.is_file():
        return 0

    original = path.read_text(encoding="utf-8", errors="replace")

    def replace_id(match: re.Match[str]) -> str:
        quote = match.group("quote")
        component_id = match.group("id")
        return f".id({quote}ohosVideoComponent_{component_id}{quote})"

    patched, count = re.subn(
        r"\.id\(\s*(?P<quote>['\"])(?P<id>"
        + "|".join(re.escape(item) for item in sorted(ORANGE_SHOPPING_VIDEO_COMPONENT_IDS))
        + r")(?P=quote)\s*\)",
        replace_id,
        original,
    )
    if count:
        path.write_text(patched, encoding="utf-8")
    return count


