def format_path_for_display(
    path_value: str | os.PathLike[str],
    *,
    start: str | os.PathLike[str] | None = None,
) -> str:
    path = Path(path_value).expanduser().resolve()
    start_path = Path(start).expanduser().resolve() if start is not None else Path.cwd().resolve()

    try:
        return path.relative_to(start_path).as_posix() or "."
    except ValueError:
        try:
            return Path(os.path.relpath(path, start_path)).as_posix()
        except ValueError:
            return str(path)


def command_output(result: subprocess.CompletedProcess[str]) -> str:
    stdout = result.stdout or ""
    stderr = result.stderr or ""
    return "\n".join(part for part in (stdout, stderr) if part).strip()


def run_command(
    command: Sequence[str],
    cwd: Path,
    env: dict[str, str] | None = None,
    timeout_sec: float | None = None,
) -> subprocess.CompletedProcess[str]:
    popen_kwargs: dict[str, Any] = {
        "args": [str(part) for part in command],
        "cwd": str(cwd),
        "env": env,
        "stdout": subprocess.PIPE,
        "stderr": subprocess.PIPE,
        "text": True,
        "encoding": "utf-8",
        "errors": "replace",
    }
    if os.name == "nt":
        popen_kwargs["creationflags"] = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
    else:
        popen_kwargs["start_new_session"] = True

    proc = subprocess.Popen(**popen_kwargs)
    try:
        stdout, stderr = proc.communicate(timeout=timeout_sec)
    except subprocess.TimeoutExpired as exc:
        _kill_process_tree(proc.pid)
        try:
            stdout, stderr = proc.communicate(timeout=5)
        except subprocess.TimeoutExpired:
            stdout = exc.output if isinstance(exc.output, str) else ""
            stderr = exc.stderr if isinstance(exc.stderr, str) else ""
        raise subprocess.TimeoutExpired(
            cmd=[str(part) for part in command],
            timeout=timeout_sec,
            output=stdout,
            stderr=stderr,
        ) from exc
    return subprocess.CompletedProcess(
        [str(part) for part in command],
        proc.returncode,
        stdout,
        stderr,
    )


def _kill_process_tree(pid: int) -> None:
    if os.name == "nt":
        subprocess.run(
            ["taskkill", "/F", "/T", "/PID", str(pid)],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
        return
    try:
        os.killpg(pid, 9)
    except ProcessLookupError:
        return
    except OSError:
        try:
            os.kill(pid, 9)
        except OSError:
            return


