@dataclass(slots=True)
class StructuredToolError(Exception):
    code: str
    message: str
    details: dict[str, Any] = field(default_factory=dict)

    def __str__(self) -> str:
        output_tail = str(self.details.get("output_tail") or "").strip()
        return f"{self.message}\n{output_tail}" if output_tail else self.message

    def to_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "message": self.message,
            "details": self.details,
        }


@dataclass(frozen=True, slots=True)
class BuildVerdict:
    status: str
    effective_exit_code: int
    raw_exit_code: int
    reason: str

    @property
    def passed(self) -> bool:
        return self.status == "passed"

    def to_dict(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "effective_exit_code": self.effective_exit_code,
            "raw_exit_code": self.raw_exit_code,
            "reason": self.reason,
        }


def _normalize_error_details(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {str(key): _normalize_error_details(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_normalize_error_details(item) for item in value]
    return value


def error_to_dict(exc: BaseException) -> dict[str, Any]:
    if isinstance(exc, StructuredToolError):
        return {
            "code": exc.code,
            "message": exc.message,
            "details": _normalize_error_details(exc.details),
        }
    return {
        "code": exc.__class__.__name__,
        "message": str(exc),
        "details": {},
    }


def error_to_json(exc: BaseException) -> str:
    return json.dumps(error_to_dict(exc), ensure_ascii=False, sort_keys=True)


