def parse_dotenv_text(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue

        key, value = line.split("=", 1)
        key = key.strip()
        if not key:
            continue

        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        values[key] = value
    return values


def load_dotenv_file(
    path_value: str | os.PathLike[str],
    *,
    override: bool = False,
    env: dict[str, str] | None = None,
    encoding: str = "utf-8",
) -> dict[str, str]:
    path = resolve_existing_path(path_value, "env_file")
    values = parse_dotenv_text(path.read_text(encoding=encoding, errors="replace"))

    target_env = os.environ if env is None else env
    for key, value in values.items():
        if override or key not in target_env:
            target_env[key] = value
    return values


def read_tool_env_file(
    path_value: str | os.PathLike[str] | None = None,
    *,
    encoding: str = "utf-8",
) -> dict[str, str]:
    """Read the verification tools' dotenv file without mutating the process env."""

    env_path = Path(path_value).expanduser().resolve() if path_value else DEFAULT_TOOL_ENV_FILE
    if not env_path.is_file():
        return {}
    return parse_dotenv_text(env_path.read_text(encoding=encoding, errors="replace"))


def load_tool_env_file(
    path_value: str | os.PathLike[str] | None = None,
    *,
    override: bool = True,
    env: dict[str, str] | None = None,
    encoding: str = "utf-8",
) -> dict[str, str]:
    """Load tools/.env; callers use this as the source of truth for tool config."""

    env_path = Path(path_value).expanduser().resolve() if path_value else DEFAULT_TOOL_ENV_FILE
    if not env_path.is_file():
        return {}
    values = parse_dotenv_text(env_path.read_text(encoding=encoding, errors="replace"))
    target_env = os.environ if env is None else env
    if override:
        for key in list(target_env):
            if key.startswith("HARMONY_") or key.startswith("DEVECO_PATH_") or key in TOOL_CONFIG_ENV_NAMES:
                if key not in values:
                    del target_env[key]
    for key, value in values.items():
        if override or key not in target_env:
            target_env[key] = value
    return values


def build_tool_process_env(base_env: Mapping[str, str] | None = None) -> dict[str, str]:
    """Return process env overlaid with tools/.env values.

    The surrounding shell is still inherited for generic OS variables, but Harmony
    tool configuration such as DevEco, SDK, Node, and ohpm paths comes from
    tools/.env and wins over same-named shell variables.
    """

    env = dict(os.environ if base_env is None else base_env)
    for key in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"):
        env.pop(key, None)
    tool_values = read_tool_env_file()
    for key in list(env):
        if key.startswith("HARMONY_") or key.startswith("DEVECO_PATH_") or key in TOOL_CONFIG_ENV_NAMES:
            if key not in tool_values:
                del env[key]
    env.update(tool_values)
    return env


def _first_non_empty_text(*values: object | None) -> str | None:
    for value in values:
        if value is None:
            continue
        text = str(value).strip()
        if text:
            return text
    return None


def _deveco_profile_token(profile: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", profile.strip()).strip("_").upper()


def resolve_deveco_path_setting(
    explicit: str | os.PathLike[str] | None = None,
    *,
    default: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
) -> str | None:
    """Resolve DevEco path from an explicit value or the selected env profile."""

    if explicit_text := _first_non_empty_text(explicit):
        return explicit_text

    source_env = build_tool_process_env() if env is None else env
    profile = _first_non_empty_text(source_env.get("HARMONY_DEVECO_PROFILE"), source_env.get("DEVECO_PROFILE"))
    if profile:
        token = _deveco_profile_token(profile)
        if not token:
            raise ValueError(f"Invalid DevEco profile name: {profile!r}")
        profile_keys = (
            f"HARMONY_DEVECO_PATH_{token}",
            f"DEVECO_PATH_{token}",
            f"HARMONY_DEVECO_{token}_PATH",
            f"DEVECO_{token}_PATH",
        )
        for key in profile_keys:
            if value := _first_non_empty_text(source_env.get(key)):
                return value
        raise ValueError(
            f"DevEco profile {profile!r} is selected, but none of these env vars are set: "
            + ", ".join(profile_keys)
        )

    return _first_non_empty_text(
        source_env.get("HARMONY_DEVECO_PATH"),
        source_env.get("DEVECO_PATH"),
        default,
    )


def strip_ansi(text: str) -> str:
    return ANSI_ESCAPE_RE.sub("", text)


def classify_build_output(raw_exit_code: int, output_text: str) -> BuildVerdict:
    normalized = strip_ansi(output_text or "")
    if any(marker in normalized for marker in BUILD_FAILURE_MARKERS):
        return BuildVerdict(
            status="failed",
            effective_exit_code=1,
            raw_exit_code=raw_exit_code,
            reason="failure_marker",
        )
    if any(marker in normalized for marker in BUILD_SUCCESS_MARKERS):
        return BuildVerdict(
            status="passed",
            effective_exit_code=0,
            raw_exit_code=raw_exit_code,
            reason="success_marker",
        )
    if raw_exit_code == 0:
        return BuildVerdict(
            status="passed",
            effective_exit_code=0,
            raw_exit_code=raw_exit_code,
            reason="raw_exit_zero",
        )
    return BuildVerdict(
        status="failed",
        effective_exit_code=raw_exit_code or 1,
        raw_exit_code=raw_exit_code,
        reason="raw_exit_nonzero",
    )


def tail_text(text: str, limit: int = 60) -> str:
    lines = [line.rstrip() for line in strip_ansi(text).splitlines()]
    if len(lines) <= limit:
        return "\n".join(lines).strip()
    return "\n".join(lines[-limit:]).strip()


