def _repo_oh_package_paths(repo_dir: Path) -> list[Path]:
    """Return root/module ``oh-package.json5`` files declared by the Harmony project."""
    paths: list[Path] = []
    seen: set[str] = set()

    def add(path: Path) -> None:
        resolved = path.resolve()
        key = str(resolved).lower()
        if key not in seen and resolved.is_file():
            seen.add(key)
            paths.append(resolved)

    add(repo_dir / "oh-package.json5")
    build_profile = repo_dir / "build-profile.json5"
    if not build_profile.is_file():
        return paths
    try:
        data = parse_json5_text(build_profile.read_text(encoding="utf-8", errors="replace"))
    except Exception:
        return paths
    modules = data.get("modules") if isinstance(data, dict) else None
    if not isinstance(modules, list):
        return paths
    for module in modules:
        if not isinstance(module, dict):
            continue
        src_path = module.get("srcPath")
        if isinstance(src_path, str) and src_path.strip():
            add(repo_dir / src_path / "oh-package.json5")
    return paths


def _is_registry_dependency_spec(spec: Any) -> bool:
    if not isinstance(spec, str):
        return False
    normalized = spec.strip().lower()
    if not normalized:
        return False
    return not (
        normalized.startswith("file:")
        or normalized.startswith("../")
        or normalized.startswith("./")
        or normalized.startswith("/")
        or re.match(r"^[a-z]:[\\/]", normalized)
    )


OHPM_SEMVER_RANGE_MIN_RE = re.compile(
    r"^\s*(?:\^|~|>=|=)\s*"
    r"(?P<version>\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?)"
)


def _minimum_version_from_ohpm_range(spec: Any) -> str | None:
    if not isinstance(spec, str):
        return None
    stripped = spec.strip()
    if not stripped or "||" in stripped:
        return None
    match = OHPM_SEMVER_RANGE_MIN_RE.match(stripped)
    if not match:
        return None
    version = match.group("version")
    return None if stripped == version else version


def _apply_api_compatible_ohpm_adapters(
    repo_dir: Path,
    *,
    product_name: str = "default",
) -> tuple[dict[Path, str], list[str]]:
    """
    Apply temporary ohpm dependency pins needed by older SDK projects.

    Some upstream packages publish newer compatibleSdkVersion requirements under
    a broad semver range. For example, ``@ohos/zxing@^2.0.0`` can now resolve
    to a newer HAR whose SDK floor no longer matches the base project. During
    install we pin registry semver ranges to their declared minimum version,
    then restore source manifests so environment adaptation does not enter
    patches.
    """
    _ = product_name

    backups: dict[Path, str] = {}
    notes: list[str] = []

    for pkg_path in _repo_oh_package_paths(repo_dir):
        try:
            original = pkg_path.read_text(encoding="utf-8", errors="replace")
            data = parse_json5_text(original)
        except Exception:
            continue
        if not isinstance(data, dict):
            continue

        changed = False
        for section_name in ("dependencies", "dynamicDependencies", "devDependencies"):
            section = data.get(section_name)
            if not isinstance(section, dict):
                continue
            for package_name, spec in list(section.items()):
                minimum_version = _minimum_version_from_ohpm_range(spec)
                if _is_registry_dependency_spec(spec) and minimum_version is not None:
                    section[package_name] = minimum_version
                    changed = True
                    notes.append(
                        "OHPM_ADAPTER=pin_minimum "
                        f"{package_name} {spec!r}->{minimum_version!r} "
                        f"in {format_path_for_display(pkg_path, start=repo_dir)}"
                    )

        if changed:
            backups[pkg_path] = original
            pkg_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    return backups, notes


def _snapshot_files(paths: Iterable[Path]) -> dict[Path, str | None]:
    snapshots: dict[Path, str | None] = {}
    for path in paths:
        resolved = path.resolve()
        if resolved.is_file():
            snapshots[resolved] = resolved.read_text(encoding="utf-8", errors="replace")
        else:
            snapshots[resolved] = None
    return snapshots


def _restore_file_snapshots(snapshots: Mapping[Path, str | None]) -> list[str]:
    notes: list[str] = []
    for path, content in snapshots.items():
        try:
            if content is None:
                if path.exists():
                    path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        except Exception as exc:
            notes.append(f"OHPM_ADAPTER_RESTORE_ERROR={path}: {exc}")
    return notes


def _snapshot_binary_files(paths: Iterable[Path]) -> dict[Path, bytes | None]:
    snapshots: dict[Path, bytes | None] = {}
    for path in paths:
        resolved = path.resolve()
        snapshots[resolved] = resolved.read_bytes() if resolved.is_file() else None
    return snapshots


def _restore_binary_file_snapshots(snapshots: Mapping[Path, bytes | None]) -> list[str]:
    notes: list[str] = []
    for path, content in snapshots.items():
        try:
            if content is None:
                if path.exists():
                    path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
        except Exception as exc:
            notes.append(f"OHPM_ADAPTER_RESTORE_ERROR={path}: {exc}")
    return notes


def run_ohpm_install(
    repo_dir: str | os.PathLike[str],
    deveco_path: str | os.PathLike[str],
    *,
    timeout_sec: float | None,
    product_name: str = "default",
) -> tuple[int, str]:
    """
    Run ``ohpm install`` as a deterministic repo initialization step before build/test.
    """
    resolved_repo = resolve_directory(repo_dir, "repo_dir")
    resolved_deveco = resolve_directory(deveco_path, "deveco_path")
    ohpm = find_ohpm(resolved_deveco)
    command = [str(ohpm), "install"]
    lock_paths = [path.parent / "oh-package-lock.json5" for path in _repo_oh_package_paths(resolved_repo)]
    lock_snapshots = _snapshot_files(lock_paths)
    manifest_backups: dict[Path, str] = {}
    archive_snapshots: dict[Path, bytes | None] = {}
    adapter_notes: list[str] = []
    restore_notes: list[str] = []
    env = build_harmony_command_env(
        sdk_root=None,
        deveco_path=resolved_deveco,
        base_env=os.environ.copy(),
    )
    try:
        adapter_notes.extend(_prepare_orange_shopping_lfs_hars(resolved_repo))
        local_archives = _repo_local_ohpm_archive_paths(resolved_repo)
        archive_snapshots = _snapshot_binary_files(local_archives)
        adapter_notes.extend(_prepare_local_archive_dependency_lock_pins(resolved_repo, local_archives))
        manifest_backups, ohpm_adapter_notes = _apply_api_compatible_ohpm_adapters(
            resolved_repo,
            product_name=product_name,
        )
        adapter_notes.extend(ohpm_adapter_notes)
        result = run_command(command, cwd=resolved_repo, env=env, timeout_sec=timeout_sec)
    finally:
        restore_notes.extend(_restore_file_snapshots({path: text for path, text in manifest_backups.items()}))
        restore_notes.extend(_restore_file_snapshots(lock_snapshots))
        restore_notes.extend(_restore_binary_file_snapshots(archive_snapshots))
    output_text = command_output(result)
    status = "SUCCESS" if result.returncode == 0 else "FAILED"
    combined = "\n".join(
        [
            f"OHPM_STATUS={status}",
            f"OHPM_EXIT_CODE={result.returncode}",
            f"OHPM_COMMAND={format_command(command)}",
            *adapter_notes,
            output_text.strip(),
            *restore_notes,
        ]
    ).strip()
    return result.returncode, combined + "\n"


def _abi_filter_text_with_x86_64(text: str, *, only_x86_64: bool = False) -> str:
    pattern = re.compile(r'("abiFilters"\s*:\s*\[)(?P<body>.*?)(\])', re.S)
    match = pattern.search(text)
    if not match:
        return text
    body = match.group("body")
    if only_x86_64:
        new_body = '\n        "x86_64"\n      '
        return text[: match.start("body")] + new_body + text[match.end("body") :]
    if re.search(r'["\']x86_64["\']', body):
        return text
    stripped = body.rstrip()
    if stripped:
        suffix = "" if stripped.endswith(",") else ","
        new_body = f'{stripped}{suffix}\n        "x86_64"\n      '
    else:
        new_body = '\n        "x86_64"\n      '
    return text[: match.start("body")] + new_body + text[match.end("body") :]


