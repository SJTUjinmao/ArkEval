def build_harmony_command_env(
    *,
    sdk_root: Path | None,
    sdk_api_level: int | None = None,
    deveco_path: str | os.PathLike[str],
    base_env: Mapping[str, str] | None = None,
) -> dict[str, str]:
    env = dict(base_env or os.environ)
    if sdk_root:
        # Pass the parent SDK root to hvigor and let compileSdkVersion drive API selection.
        # Some hvigor versions mis-detect components when pointed directly at ``.../Sdk/<api>``.
        sdk_s = str(Path(sdk_root).expanduser().resolve())
        env["DEVECO_SDK_HOME"] = sdk_s
        env["OHOS_BASE_SDK_HOME"] = sdk_s
        env["OHOS_SDK_HOME"] = sdk_s

    node_home = find_node_home(deveco_path)
    java_home = find_java_home(deveco_path)
    path_prefixes: list[str] = []
    if java_home:
        env["JAVA_HOME"] = str(java_home)
        path_prefixes.append(str(java_home / "bin"))
    if node_home:
        env["NODE_HOME"] = str(node_home)
        path_prefixes.append(str(node_home))
    if path_prefixes:
        env["PATH"] = os.pathsep.join([*path_prefixes, env.get("PATH", "")]).strip(os.pathsep)
    return env


@dataclass(slots=True)
class StructuredToolError(Exception):
    code: str
    message: str
    details: dict[str, Any] = field(default_factory=dict)

    def __str__(self) -> str:
        return self.message

    def to_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "message": self.message,
            "details": self.details,
        }


def _normalize_error_details(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {str(key): _normalize_error_details(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_normalize_error_details(item) for item in value]
    return value


def error_to_dict(exc: BaseException) -> dict[str, Any]:
    if isinstance(exc, StructuredToolError):
        return {
            "code": exc.code,
            "message": exc.message,
            "details": _normalize_error_details(exc.details),
        }
    return {
        "code": exc.__class__.__name__,
        "message": str(exc),
        "details": {},
    }


def error_to_json(exc: BaseException) -> str:
    return json.dumps(error_to_dict(exc), ensure_ascii=False, sort_keys=True)


def resolve_directory(path_value: str | os.PathLike[str], label: str) -> Path:
    path = Path(path_value).expanduser().resolve()
    if not path.is_dir():
        raise FileNotFoundError(f"{label} does not exist or is not a directory: {path}")
    return path


def resolve_existing_path(path_value: str | os.PathLike[str], label: str) -> Path:
    path = Path(path_value).expanduser().resolve()
    if not path.exists():
        raise FileNotFoundError(f"{label} does not exist: {path}")
    return path


