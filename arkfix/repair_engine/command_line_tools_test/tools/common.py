def _is_git_lfs_pointer(path: Path) -> bool:
    if not path.is_file() or path.stat().st_size > 1024:
        return False
    try:
        head = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return False
    return head.startswith("version https://git-lfs.github.com/spec/v1")


def _find_orange_shopping_full_har(repo_dir: Path, file_name: str) -> Path | None:
    workspace_root = repo_dir
    for parent in repo_dir.parents:
        if parent.name == "arkagent":
            workspace_root = parent
            break

    candidates = [
        workspace_root / "repair_repo" / "applications_app_samples",
        workspace_root / "repair_repo_parallel",
        workspace_root / "test_repo",
        workspace_root / "data_files",
    ]
    relative_tail = Path("code") / "Solutions" / "Shopping" / "OrangeShopping" / "libs" / file_name

    for root in candidates:
        if not root.exists():
            continue
        if root.name in {"repair_repo_parallel", "test_repo"}:
            for run_dir in sorted(root.glob("run*")):
                path = run_dir / "applications_app_samples" / relative_tail
                if path.is_file() and path.stat().st_size > 1024:
                    return path
            continue
        path = root / relative_tail
        if path.is_file() and path.stat().st_size > 1024:
            return path
        try:
            for path in root.rglob(file_name):
                if path.is_file() and path.stat().st_size > 1024:
                    return path
        except OSError:
            continue
    return None


