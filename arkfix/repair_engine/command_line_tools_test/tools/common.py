def find_node_home(deveco_path: str | os.PathLike[str]) -> Path | None:
    if shutil.which("node"):
        return None

    base_path = resolve_directory(deveco_path, "deveco_path")
    executable_name = "node.exe" if os.name == "nt" else "node"
    candidates = _existing_paths(
        [
            base_path / "tools" / "node",
            base_path / "node",
        ]
    )
    for candidate in candidates:
        if (candidate / executable_name).exists():
            return candidate

    recursive_match = next(base_path.rglob(executable_name), None)
    if recursive_match:
        return recursive_match.parent.resolve()

    return None


def find_java_home(deveco_path: str | os.PathLike[str]) -> Path | None:
    """Use DevEco-bundled JBR when ``java`` is not on PATH (fixes hvigor ``spawn java ENOENT`` on Windows CLI)."""
    env_jh = os.environ.get("JAVA_HOME", "").strip()
    if env_jh:
        home = Path(env_jh).expanduser().resolve()
        executable_name = "java.exe" if os.name == "nt" else "java"
        if (home / "bin" / executable_name).is_file():
            return home
    if shutil.which("java"):
        return None

    base_path = resolve_directory(deveco_path, "deveco_path")
    executable_name = "java.exe" if os.name == "nt" else "java"
    for home_name in ("jbr", "jre"):
        home = base_path / home_name
        if (home / "bin" / executable_name).is_file():
            return home.resolve()

    jdk_bin = base_path / "tools" / "jdk" / "bin" / executable_name
    if jdk_bin.is_file():
        return jdk_bin.parent.parent.resolve()

    found = next(base_path.rglob(executable_name), None)
    if found and found.parent.name == "bin":
        return found.parent.parent.resolve()

    return None


def find_hvigor_wrapper(
    repo_path: str | os.PathLike[str],
    deveco_path: str | os.PathLike[str],
) -> Path:
    repo_dir = resolve_directory(repo_path, "repo_path")
    deveco_dir = resolve_directory(deveco_path, "deveco_path")

    wrapper_names = ("hvigorw.bat", "hvigorw") if os.name == "nt" else ("hvigorw", "hvigorw.bat")
    local_hvigor_names = ("hvigor.cmd", "hvigor") if os.name == "nt" else ("hvigor", "hvigor.cmd")

    repo_candidates = [
        *[repo_dir / name for name in wrapper_names],
        *[repo_dir / "node_modules" / ".bin" / name for name in local_hvigor_names],
    ]
    deveco_candidates = [
        deveco_dir / "tools" / "hvigor" / "bin" / "hvigorw.bat",
        deveco_dir / "tools" / "hvigor" / "bin" / "hvigorw",
        deveco_dir / "hvigorw.bat",
        deveco_dir / "hvigorw",
    ]

    for candidate in repo_candidates + deveco_candidates:
        if candidate.exists():
            return candidate.resolve()

    for name in wrapper_names:
        found_in_path = shutil.which(name)
        if found_in_path:
            return Path(found_in_path).resolve()

    for name in wrapper_names:
        recursive_match = next(deveco_dir.rglob(name), None)
        if recursive_match:
            return recursive_match.resolve()

    raise FileNotFoundError(
        "Unable to find hvigorw/hvigorw.bat under the repo, the provided DevEco Studio path, or PATH."
    )
