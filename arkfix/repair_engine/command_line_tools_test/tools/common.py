def _prepare_legacy_hvigor_sdk_view(repo_dir: Path, sdk_root: Path, *, api_level: int) -> Path | None:
    api_slice = resolve_sdk_api_slice_for_api(sdk_root, api_level)
    if not api_slice.is_dir():
        return None

    sources: list[tuple[str, str, Path]] = []
    for component in ("ets", "js", "native", "previewer", "toolchains"):
        src = api_slice / component
        package_json = src / "oh-uni-package.json"
        if not package_json.is_file():
            continue
        try:
            data = json.loads(package_json.read_text(encoding="utf-8", errors="replace"))
        except Exception:
            continue
        version = str(data.get("version") or "").strip()
        if version:
            sources.append((component, version, src.resolve()))

    if not sources:
        return None

    view_root = repo_dir / f".arkagent_legacy_sdk_api{api_level}"
    _safe_remove_generated_dir(view_root, owner=repo_dir)
    view_root.mkdir(parents=True, exist_ok=True)
    (view_root / ".generated-by-arkagent").write_text(
        f"legacy hvigor sdk view for API {api_level}\nsource={api_slice}\n",
        encoding="utf-8",
    )
    for component, version, src in sources:
        dest = view_root / component / version
        if (
            component == "ets"
            and api_level >= 10
            and repo_dir.as_posix().replace("\\", "/").endswith("/ETSUI/QRCode")
        ):
            _prepare_legacy_ets_component_with_test_runner_shim(src, dest, api_level=api_level)
        else:
            _link_legacy_sdk_component(src, dest)
    return view_root


